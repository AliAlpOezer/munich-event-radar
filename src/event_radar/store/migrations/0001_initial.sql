-- The radar's tables (ADR 0002, 0004-0006). Runs with search_path = <store schema>, pg_temp,
-- after the Supabase shim. Supabase never exposes this schema: the page reads it only through
-- the security-invoker views and functions of api.sql (ADR 0005).

-- The registry: who organises events, and the pages the harvester watches.

CREATE TABLE organiser (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    domain text NOT NULL,
    homepage text,
    kind text,
    ai_focus boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'demoted', 'removed', 'dormant')),
    discovered_via text NOT NULL,
    discovered_at timestamptz NOT NULL,
    discovery_url text,
    UNIQUE (domain, name)
);

CREATE TABLE source (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organiser_id bigint REFERENCES organiser (id),
    url text NOT NULL UNIQUE,
    kind text NOT NULL CHECK (kind IN ('feed', 'listing', 'event_page')),
    source_class text NOT NULL CHECK (source_class IN ('TICKET', 'OWN', 'AGG')),
    browser boolean NOT NULL DEFAULT false,
    cadence_hours integer NOT NULL,
    added_at timestamptz NOT NULL,
    added_via text NOT NULL,
    last_fetched_at timestamptz,
    last_ok_at timestamptz,
    last_yield integer,
    max_yield integer NOT NULL DEFAULT 0,
    empty_streak integer NOT NULL DEFAULT 0,
    error_streak integer NOT NULL DEFAULT 0,
    last_error text
);

-- Fetching: a snapshot row per fetch, the body by content hash. A runner's disk is gone after
-- each job, so bodies live here (ADR 0006 D2). stored_at protects a body a running job has
-- just written from the pruning another job does (Pages.prune).

CREATE TABLE snapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url text NOT NULL,
    content_hash text,
    fetched_at timestamptz NOT NULL,
    http_status integer,
    content_type text,
    etag text,
    last_modified text,
    error text
);
CREATE INDEX snapshot_by_url ON snapshot (url, fetched_at);

CREATE TABLE page_body (
    content_hash text PRIMARY KEY,
    body bytea NOT NULL,
    stored_at timestamptz NOT NULL DEFAULT now()
);

-- Extraction: what each page said, the LLM's answers cached by content hash, its queue and
-- its daily budget.

CREATE TABLE observation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_hash text NOT NULL,
    url text NOT NULL,
    source_class text NOT NULL,
    method text NOT NULL,
    item integer NOT NULL,
    platform_keys jsonb NOT NULL,
    fields jsonb NOT NULL,
    links jsonb NOT NULL,
    observed_at timestamptz NOT NULL,
    UNIQUE (snapshot_hash, url, method, item)
);

CREATE TABLE extraction (
    content_hash text NOT NULL,
    version text NOT NULL,
    model text NOT NULL,
    result jsonb NOT NULL,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (content_hash, version)
);

CREATE TABLE extraction_job (
    snapshot_hash text NOT NULL,
    url text NOT NULL,
    priority integer NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'done', 'needs_look')),
    PRIMARY KEY (snapshot_hash, url)
);

CREATE TABLE budget (
    provider text NOT NULL,
    day date NOT NULL,
    used integer NOT NULL DEFAULT 0,
    PRIMARY KEY (provider, day)
);

-- Events, judged from the observations; an alias keeps an old key pointing at its event.

CREATE TABLE event (
    key text PRIMARY KEY,
    fields jsonb NOT NULL,
    merge_basis text NOT NULL,
    tier text,
    tier_reasons jsonb,
    drop_reason text,
    sources jsonb NOT NULL DEFAULT '[]',
    first_seen timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE event_alias (
    alias text PRIMARY KEY,
    event_key text NOT NULL REFERENCES event (key)
);
CREATE INDEX event_alias_by_event ON event_alias (event_key);

CREATE TABLE push_ledger (
    event_key text NOT NULL,
    kind text NOT NULL,
    fact_hash text NOT NULL,
    state text NOT NULL CHECK (state IN ('pending', 'sent')),
    created_at timestamptz NOT NULL,
    sent_at timestamptz,
    message_id text,
    UNIQUE (event_key, kind, fact_hash)
);

-- People: admins, and each user's status per event (ADR 0005).

CREATE TABLE admin (
    user_id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('owner', 'admin')),
    added_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX admin_one_owner ON admin (role) WHERE role = 'owner';

CREATE TABLE user_state (
    user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    event_key text NOT NULL REFERENCES event (key) ON DELETE CASCADE,
    status text NOT NULL CHECK (status IN ('none', 'applied', 'registered', 'skipped')),
    feedback integer,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, event_key)
);
CREATE INDEX user_state_by_event ON user_state (event_key);

-- Statuses from before logins existed wait here until `grant-admin --owner` claims them.
CREATE TABLE user_state_unclaimed (
    event_key text PRIMARY KEY REFERENCES event (key) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'none'
        CHECK (status IN ('none', 'applied', 'registered', 'skipped')),
    feedback integer,
    updated_at timestamptz NOT NULL
);

-- The one authority on status changes. A new row may hold any status, since every status is
-- reachable from 'none'; that also keeps INSERT ... ON CONFLICT DO UPDATE usable.
CREATE FUNCTION check_status_transition() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF (OLD.status, NEW.status) NOT IN (
        ('none', 'applied'), ('none', 'registered'), ('none', 'skipped'),
        ('applied', 'registered'), ('applied', 'skipped'), ('applied', 'none'),
        ('registered', 'none'), ('skipped', 'none')
    ) THEN
        RAISE EXCEPTION '% cannot become %', OLD.status, NEW.status
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER status_transition BEFORE UPDATE OF status ON user_state FOR EACH ROW
    WHEN (OLD.status IS DISTINCT FROM NEW.status) EXECUTE FUNCTION check_status_transition();
CREATE TRIGGER status_transition BEFORE UPDATE OF status ON user_state_unclaimed FOR EACH ROW
    WHEN (OLD.status IS DISTINCT FROM NEW.status) EXECUTE FUNCTION check_status_transition();

-- Intake: adding an organisation (ADR 0003). A user's suggestion waits in 'review' for an
-- admin; an intake becoming 'queued' starts the intake workflow (ADR 0006 D3).

CREATE TABLE intake (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url text NOT NULL,
    events_url text,
    name text,
    state text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'checking', 'profiling',
        'review', 'finding', 'harvesting', 'done', 'rejected', 'failed')),
    approved boolean NOT NULL DEFAULT false,
    profile jsonb,
    log jsonb NOT NULL DEFAULT '[]',
    result jsonb,
    organiser_id bigint REFERENCES organiser (id),
    error text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    submitted_by uuid REFERENCES auth.users (id) ON DELETE SET NULL
);
CREATE INDEX intake_in_review_by_user ON intake (submitted_by) WHERE state = 'review';

-- pg_net sends the request after commit, so the workflow never starts before the row exists.
-- Without both Vault secrets (a local or test database) nothing is sent; the workflow's
-- hourly schedule then works the queue.
CREATE FUNCTION dispatch_intake_workflow() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT AS $$
DECLARE
    target text := (SELECT decrypted_secret FROM vault.decrypted_secrets
                    WHERE name = 'intake_dispatch_url');
    token text := (SELECT decrypted_secret FROM vault.decrypted_secrets
                   WHERE name = 'intake_dispatch_token');
BEGIN
    IF target IS NULL OR token IS NULL THEN
        RETURN NULL;
    END IF;
    PERFORM net.http_post(
        url := target,
        body := '{"ref": "main"}'::jsonb,
        headers := jsonb_build_object(
            'Authorization', 'Bearer ' || token,
            'Accept', 'application/vnd.github+json',
            'Content-Type', 'application/json',
            'User-Agent', 'munich-event-radar'
        )
    );
    RETURN NULL;
END
$$;
CREATE TRIGGER intake_queued AFTER INSERT ON intake FOR EACH ROW
    WHEN (NEW.state = 'queued') EXECUTE FUNCTION dispatch_intake_workflow();
CREATE TRIGGER intake_requeued AFTER UPDATE OF state ON intake FOR EACH ROW
    WHEN (NEW.state = 'queued' AND OLD.state IS DISTINCT FROM 'queued')
    EXECUTE FUNCTION dispatch_intake_workflow();

-- One entry for intake.log, in the shape Intakes.log writes.
CREATE FUNCTION intake_log_entry(step text, text text, level text) RETURNS jsonb
LANGUAGE sql STABLE SET search_path FROM CURRENT AS $$
    SELECT jsonb_build_array(jsonb_build_object(
        'at', to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"+00:00"'),
        'step', step, 'text', text, 'level', level
    ))
$$;

CREATE TABLE run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    outcome text,
    summary jsonb
);

-- Access (ADR 0005). A definer, so it answers false for anon, who cannot read the admin table.
CREATE FUNCTION is_admin() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path FROM CURRENT AS $$
    SELECT EXISTS (SELECT FROM admin WHERE user_id = auth.uid())
$$;

-- Staleness is public, the run log is not: this returns one timestamp and nothing else.
CREATE FUNCTION last_ok_run_at() RETURNS timestamptz
LANGUAGE sql STABLE SECURITY DEFINER SET search_path FROM CURRENT AS $$
    SELECT max(started_at) FROM run WHERE outcome = 'ok'
$$;

REVOKE ALL ON FUNCTION check_status_transition(), dispatch_intake_workflow(), is_admin(),
    last_ok_run_at(), intake_log_entry(text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION is_admin(), last_ok_run_at() TO anon, authenticated;

